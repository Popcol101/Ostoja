// Service worker panelu Ostoi: tylko powiadomienia push (bez pamięci podręcznej stron).
self.addEventListener("push", (event) => {
  let data = { title: "Ostoja", body: "Nowe powiadomienie", url: "/panel/zapytania", tag: "ostoja" };
  try {
    data = { ...data, ...event.data.json() };
  } catch (e) {}
  event.waitUntil(
    self.registration.showNotification(data.title, {
      body: data.body,
      tag: data.tag,
      renotify: true,
      requireInteraction: true,
      icon: "/brand/ostoja-ikona-192.png",
      badge: "/brand/ostoja-znak-maly.svg",
      data: { url: data.url },
    }),
  );
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url = new URL(event.notification.data?.url || "/panel/zapytania", self.location.origin).href;
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((list) => {
      for (const client of list) {
        if (client.url.startsWith(self.location.origin) && "focus" in client) {
          client.navigate(url);
          return client.focus();
        }
      }
      return self.clients.openWindow(url);
    }),
  );
});
